// Minutes for a service name, or undefined when nothing is known (the duration is then left as it is).
export function durationFor(name) {
  const text = String(name || '').trim()
  const inName = text.match(/(\d+)\s*分钟/)
  if (inName) return Number(inName[1])
  return DEFAULTS[text]
}
